export function fnv1a(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    const ch = s.charCodeAt(i);
    // 处理非 ASCII 字符：按 UTF-8 字节做 FNV-1a（与生成脚本一致）
    const bytes = ch < 0x80 ? [ch] : ch < 0x800 ? [0xc0 | (ch >> 6), 0x80 | (ch & 63)] : [0xe0 | (ch >> 12), 0x80 | ((ch >> 6) & 63), 0x80 | (ch & 63)];
    for (const b of bytes) {
      h ^= b;
      h = Math.imul(h, 0x01000193) >>> 0;
    }
  }
  return h.toString(16).padStart(8, "0");
}

export function blessingIndexFor(hash: string): number {
  return parseInt(hash, 16) % BLESSINGS.length;
}

export function blessingFor(hash: string): string {
  return BLESSINGS[blessingIndexFor(hash)];
}

export function blessingByIndex(index: number): string {
  return BLESSINGS[index] ?? BLESSINGS[0];
}
